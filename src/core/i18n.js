const DICT = { it, en };
let lang = 'en';

export function resolveLang(pref) {
  if (pref === 'it' || pref === 'en') return pref;
  const n = String((typeof navigator !== 'undefined' && navigator.language) || 'en').toLowerCase();
  return n.startsWith('it') ? 'it' : 'en';
}

export function setLang(pref) {
  lang = resolveLang(pref);
  if (typeof document !== 'undefined') document.documentElement.lang = lang;
  return lang;
}

export const getLang = () => lang;

export function t(key, vars) {
  let s;
  if (vars && typeof vars.n === 'number') s = DICT[lang][`${key}.${vars.n === 1 ? 'one' : 'other'}`];
  s ??= DICT[lang][key] ?? DICT.en[key] ?? key;
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

export function greeting(date = new Date()) {
  const h = date.getHours();
  const k = h < 5 ? 'night' : h < 12 ? 'morning' : h < 18 ? 'afternoon' : 'evening';
  return t(`greet.${k}`);
}

export function relativeTime(ts) {
  const diff = ts - Date.now();
  const abs = Math.abs(diff);
  if (abs < 45e3) return t('time.now');
  const rtf = new Intl.RelativeTimeFormat(lang, { numeric: 'auto' });
  const MIN = 6e4;
  const HOUR = 60 * MIN;
  const DAY = 24 * HOUR;
  if (abs < HOUR) return rtf.format(Math.round(diff / MIN), 'minute');
  if (abs < DAY) return rtf.format(Math.round(diff / HOUR), 'hour');
  if (abs < 7 * DAY) return rtf.format(Math.round(diff / DAY), 'day');
  if (abs < 30 * DAY) return rtf.format(Math.round(diff / (7 * DAY)), 'week');
  return rtf.format(Math.round(diff / (30 * DAY)), 'month');
}

// Per le parti statiche dell'HTML: data-i18n="chiave", data-i18n-attr="placeholder:chiave;title:chiave".
export function applyStatic(root = document) {
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-attr]')) {
    for (const pair of el.dataset.i18nAttr.split(';')) {
      const [attr, key] = pair.split(':');
      if (attr && key) el.setAttribute(attr.trim(), t(key.trim()));
    }
  }
}
